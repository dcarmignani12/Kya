// npm run setup            (add `-- --reset` to drop and recreate all KYA tables)
//   1. Generates Ed25519 keys into .env (only those that are missing):
//        AGENT_PRIVATE_KEY      – Atlas's signing key (the agent's secret)
//        KYA_PRIVATE_KEY        – the KYA service's assertion-signing key
//        PRINCIPAL_PRIVATE_KEY  – Alex Morgan's key, used here once to sign the delegation credential
//   2. Applies db/schema.sql.
//   3. Registers agt_atlas_001 in kya_agents with its *public* key and the
//      principal-signed delegation credential for mandate mdt_alex_milan_1115.
import { generateKeyPairSync } from "node:crypto";
import { existsSync, readFileSync, appendFileSync, writeFileSync } from "node:fs";
import pg from "pg";
import { AGENT_ID, AGENT_KEY_ID, MANDATE, PRINCIPAL_ID, PRINCIPAL_NAME } from "../src/lib/domain";
import { b64url, privateKeyFromEnvJwk, publicJwkOf, signJws } from "../src/server/crypto.server";

const ENV_FILE = ".env";
if (!existsSync(ENV_FILE)) writeFileSync(ENV_FILE, "# AgentTrip secrets – generated by `npm run setup`. Never commit this file.\n");
process.loadEnvFile(ENV_FILE);

function ensure(name: string, make: () => string) {
  if (process.env[name]) return;
  const value = make();
  appendFileSync(ENV_FILE, `${name}=${value}\n`);
  process.env[name] = value;
  console.log(`  + generated ${name}`);
}

const newEd25519 = () => {
  const { privateKey } = generateKeyPairSync("ed25519");
  return b64url(JSON.stringify(privateKey.export({ format: "jwk" })));
};

console.log("• keys");
ensure("DATABASE_URL", () => "postgres://agenttrip:agenttrip@localhost:5432/agenttrip");
ensure("AGENT_PRIVATE_KEY", newEd25519);
ensure("KYA_PRIVATE_KEY", newEd25519);
ensure("PRINCIPAL_PRIVATE_KEY", newEd25519);
if (!process.env.ANTHROPIC_API_KEY) console.log("  ! ANTHROPIC_API_KEY is not set – add it to .env to run the agent");

const agentPub = publicJwkOf(privateKeyFromEnvJwk(process.env.AGENT_PRIVATE_KEY!));
const principalKey = privateKeyFromEnvJwk(process.env.PRINCIPAL_PRIVATE_KEY!);
const principalPub = publicJwkOf(principalKey);

const client = new pg.Client({ connectionString: process.env.DATABASE_URL });
await client.connect();
try {
  if (process.argv.includes("--reset")) {
    console.log("• reset: dropping KYA tables");
    await client.query("DROP TABLE IF EXISTS kya_bookings, kya_approvals, kya_ledger, kya_agents CASCADE");
  }
  console.log("• schema");
  await client.query(readFileSync("db/schema.sql", "utf8"));

  console.log("• registry");
  const iat = Math.floor(Date.now() / 1000);
  const credential = signJws(
    { alg: "EdDSA", typ: "kya-delegation+jws", kid: `${PRINCIPAL_ID}#key-1` },
    { iss: PRINCIPAL_ID, sub: AGENT_ID, iat, exp: Math.floor(Date.parse(MANDATE.valid_until) / 1000), typ: "AgentDelegationCredential", mandate: MANDATE },
    principalKey,
  );
  await client.query(
    `INSERT INTO kya_agents (agent_id, display_name, operator, principal_id, principal_name, key_id, public_key_jwk, principal_public_key_jwk, delegation_credential)
     VALUES ($1, 'Atlas', 'AgentTrip Labs', $2, $3, $4, $5, $6, $7)
     ON CONFLICT (agent_id) DO UPDATE SET
       key_id = EXCLUDED.key_id, public_key_jwk = EXCLUDED.public_key_jwk,
       principal_public_key_jwk = EXCLUDED.principal_public_key_jwk,
       delegation_credential = EXCLUDED.delegation_credential, updated_at = now()`,
    [AGENT_ID, PRINCIPAL_ID, PRINCIPAL_NAME, AGENT_KEY_ID, agentPub, principalPub, credential],
  );
  const count = await client.query("SELECT count(*)::int AS n FROM kya_ledger");
  console.log(`  ${AGENT_ID} registered (key ${AGENT_KEY_ID}, x=${agentPub.x}); ledger has ${count.rows[0].n} entries`);
} finally {
  await client.end();
}
console.log("done. `npm run dev` → http://localhost:3000");
